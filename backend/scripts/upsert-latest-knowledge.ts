async function upsertItem(item: KnowledgeItem) {
  const existing = await prisma.knowledgeEntry.findFirst({
    where: { title: item.title },
    select: { id: true },
  });
  const data = {
    title: item.title,
    content: item.content.trim(),
    category: item.category,
    tags: JSON.stringify(item.tags),
    sourceName: item.sourceName,
    sourceUrl: item.sourceUrl,
    sourceDate: item.sourceDate,
    status: 'published',
  };
  if (existing) {
    await prisma.knowledgeEntry.update({ where: { id: existing.id }, data });
    return { action: 'updated', title: item.title };
  }
  await prisma.knowledgeEntry.create({ data });
  return { action: 'created', title: item.title };
}

